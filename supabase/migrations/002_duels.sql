create extension if not exists pgcrypto;

create table if not exists public.duel_rooms (
  id uuid primary key default gen_random_uuid(),
  status text not null default 'waiting' check (status in ('waiting', 'playing', 'finished')),
  letters jsonb not null,
  player_one_id text not null,
  player_two_id text,
  created_at timestamptz not null default now(),
  started_at timestamptz,
  ends_at timestamptz
);

create table if not exists public.duel_events (
  id bigint generated by default as identity primary key,
  room_id uuid not null references public.duel_rooms(id) on delete cascade,
  player_id text not null,
  word text not null,
  points integer not null,
  created_at timestamptz not null default now()
);

alter table public.duel_rooms enable row level security;
alter table public.duel_events enable row level security;

create policy "public can read duel rooms" on public.duel_rooms for select using (true);
create policy "public can create duel rooms" on public.duel_rooms for insert with check (true);
create policy "public can join duel rooms" on public.duel_rooms for update using (true) with check (true);
create policy "public can read duel events" on public.duel_events for select using (true);
create policy "public can create duel events" on public.duel_events for insert with check (true);

alter publication supabase_realtime add table public.duel_rooms;
alter publication supabase_realtime add table public.duel_events;
